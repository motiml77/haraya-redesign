android {
    namespace = "com.hourstracker.app"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.hourstracker.app"
        minSdk = 29
        targetSdk = 35
        versionCode = (System.getenv("GITHUB_RUN_NUMBER") ?: "1").toInt()
        versionName = "1.0." + (System.getenv("GITHUB_RUN_NUMBER") ?: "0")
    }

    // A fixed key (from the environment / CI secrets) lets every new build install over the previous one
    // without losing data. Without it, the release build falls back to the debug key.
    val keystorePath = System.getenv("HOURS_KEYSTORE_FILE")
    val keystorePassword = System.getenv("HOURS_KEYSTORE_PASSWORD")
    val hasReleaseKey = !keystorePath.isNullOrBlank() && !keystorePassword.isNullOrBlank() && file(keystorePath).exists()
    signingConfigs {
        if (hasReleaseKey) {
            create("app") {
                storeFile = file(keystorePath!!)
                storePassword = keystorePassword
                keyAlias = System.getenv("HOURS_KEY_ALIAS") ?: "hours"
                keyPassword = keystorePassword
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.getByName(if (hasReleaseKey) "app" else "debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
    }
    testOptions {
        unitTests.isIncludeAndroidResources = true
        // Screenshot tests (Roborazzi) write PNGs to app/screenshots/.
        unitTests.all { it.systemProperty("roborazzi.test.record", "true") }
    }
}

